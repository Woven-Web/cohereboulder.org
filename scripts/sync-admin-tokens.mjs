// Copies the design-token blocks (`:root` and `.dark`) out of src/index.css
// into worker/src/brand-tokens.generated.ts, so the server-rendered admin
// portal wears Eileen's palette from the same single source as the site.
// `npm run build` runs this; worker/src/admin-tokens.test.ts fails if the
// committed copy has drifted.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** The text of the `{ … }` block that opens at the first `selector {` found. */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`sync-admin-tokens: no "${selector} {" block in src/index.css`);
  let depth = 0;
  for (let i = css.indexOf("{", start); i < css.length; i++) {
    if (css[i] === "{") depth++;
    if (css[i] === "}" && --depth === 0) return css.slice(start, i + 1);
  }
  throw new Error(`sync-admin-tokens: unterminated "${selector}" block`);
}

export function extractTokenCss(indexCss) {
  return `${block(indexCss, ":root")}\n${block(indexCss, ".dark")}\n`;
}

const generated = (css) =>
  `// GENERATED by scripts/sync-admin-tokens.mjs from src/index.css — do not edit.\nexport const BRAND_TOKEN_CSS = ${JSON.stringify(css)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = extractTokenCss(readFileSync("src/index.css", "utf8"));
  writeFileSync("worker/src/brand-tokens.generated.ts", generated(css));
  console.log("admin tokens synced from src/index.css");
}
